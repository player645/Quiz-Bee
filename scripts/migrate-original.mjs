// Regenerates src/data/defaultQuestions.ts from legacy/original-index.html.
// Run:  npm run migrate:questions
// The original file is never modified. Difficulty labels below are INITIAL,
// UNVALIDATED judgments (they did not exist in the original); edit them freely.
import { readFileSync, writeFileSync } from 'node:fs'

const html = readFileSync(new URL('../legacy/original-index.html', import.meta.url), 'utf8')
const script = html.match(/<script>([\s\S]*)<\/script>/)[1]
const dataPart = script.split('/* ---------- helpers')[0]
const { MC, ID, CATS } = new Function(`${dataPart}; return { MC, ID, CATS }`)()

// e = easy, m = medium, h = hard. One letter per question, in original order (8 per category per type).
const DIFFICULTY = {
  History:    { mc: 'emmemhme', id: 'meeeemhh' },
  Culture:    { mc: 'mememmhe', id: 'mmehmmme' },
  Geography:  { mc: 'mememmee', id: 'mmehemhm' },
  Government: { mc: 'eeemmemm', id: 'mmemmhhh' },
}

const LONG = { e: 'easy', m: 'medium', h: 'hard' }
const PREFIX = { History: 'hist', Culture: 'cult', Geography: 'geo', Government: 'govt' }
const questions = []

for (const cat of CATS) {
  MC[cat].forEach(([text, correct, wrong, explanation], i) => {
    questions.push({
      id: `${PREFIX[cat]}-mc-${String(i + 1).padStart(2, '0')}`,
      type: 'mc', category: cat, difficulty: LONG[DIFFICULTY[cat].mc[i]],
      text, choices: [correct, ...wrong], correct, explanation, points: 1,
    })
  })
  ID[cat].forEach(([text, accepted, display, explanation], i) => {
    questions.push({
      id: `${PREFIX[cat]}-id-${String(i + 1).padStart(2, '0')}`,
      type: 'id', category: cat, difficulty: LONG[DIFFICULTY[cat].id[i]],
      text, correct: display, accepted, explanation, points: 2,
    })
  })
}

for (const cat of CATS) for (const t of ['mc', 'id']) {
  if (DIFFICULTY[cat][t].length !== 8) throw new Error(`Difficulty string for ${cat}/${t} must have 8 letters`)
}

const out = `// GENERATED by scripts/migrate-original.mjs from legacy/original-index.html. Safe to edit by hand afterwards.
// Difficulty labels are initial, unvalidated judgments added during migration.
import type { Question } from '../core/types.ts'

export const DEFAULT_QUESTIONS: Question[] = ${JSON.stringify(questions, null, 2)}
`
writeFileSync(new URL('../src/data/defaultQuestions.ts', import.meta.url), out)
console.log(`Wrote ${questions.length} questions`)
